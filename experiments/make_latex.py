    t = pd.read_csv(d / "internship_effect.csv").set_index("internship")
    m = json.loads((d / "metrics.json").read_text())
    fig, ax = plt.subplots(figsize=(3.4, 2.6))
    vals = [t.loc["Yes", "employment_rate_pct"], t.loc["No", "employment_rate_pct"]]
    ax.bar(["With\nInternship", "Without\nInternship"], vals,
           color=[CYAN, RED], edgecolor="#1a5c6e", linewidth=0.5,
           width=0.55)
    for i, v in enumerate(vals):
        ax.text(i, v + 1.5, f"{v:.2f}%", ha="center", fontsize=8)
    ci = m.get("risk_difference_ci_pp")
    ax.set_ylabel("Employment Rate (%)")
    ax.set_ylim(0, 75)
    ax.grid(axis="x", visible=False)
    txt = (f"+{m['risk_difference_pp']:.2f} pp (95% CI "
           f"{ci[0]:.2f}--{ci[1]:.2f})")
    ax.set_title(txt, fontsize=7.5)
    fig.tight_layout()
    fig.savefig(FIG / "fig5_internship.pdf", bbox_inches="tight")
    plt.close(fig)


