def tab_crosscorpus() -> None:
    """Matched-profile cross-corpus SGI (audit Phase 9/10): two corpora (HF
    Skill-Gap, LinkedIn 2024) x two academic profile sizes (P=100, P=500).

    The published diagonal is bold: ALIGN01/02 (HF, P=100) and ALIGN04
    (LinkedIn, P=500).  The off-diagonal cells are the audit reanalyses that
    hold tokenizer, model, seed and bootstrap size fixed
    (audit/_sgi_sensitivity/*.json).  Every cell is read from a committed
    artifact, so regeneration reproduces the hand-audited table byte for byte
    (asserted by tests/test_make_latex_regeneration.py)."""
    def metrics(exp_id):
        return json.loads((load(exp_id) / "metrics.json").read_text(encoding="utf-8"))

    a1 = metrics("ALIGN01_lexical_bootstrap")
    a2 = metrics("ALIGN02_semantic_sbert")
    a4 = pd.read_csv(load("ALIGN04_crosscorpus_linkedin") / "table_crosscorpus_sgi.csv")
    aud = ROOT / "audit" / "_sgi_sensitivity"
    li = json.loads((aud / "linkedin_matched_profile.json").read_text(encoding="utf-8"))
    li = li["matched_profile_results"]
    hf = json.loads((aud / "hf_acad500.json").read_text(encoding="utf-8"))

    def ci(sgi, lo, hi, bold=False):
        t = f"{sgi:.2f} [{lo:.2f}, {hi:.2f}]"
        return f"\\textbf{{{t}}}" if bold else t

    sem2 = next(r for r in a2["sensitivity"] if r["tau"] == 0.5)
    lex4 = a4[a4.method == "lexical_exact"].iloc[0]
    sem4 = a4[(a4.method == "semantic_sbert") & (a4.tau == 0.5)].iloc[0]

    # rows: matcher; columns: HF P=100 | LinkedIn P=100 | HF P=500 | LinkedIn P=500
    lex_row = " & ".join([
        ci(a1["sgi"], a1["sgi_ci_lower"], a1["sgi_ci_upper"], bold=True),
        ci(li["academic_top100"]["lexical"]["SGI"], *li["academic_top100"]["lexical"]["CI"]),
        ci(hf["lexical_sgi"], *hf["lexical_ci"]),
        ci(lex4["SGI"], lex4["CI_Lower"], lex4["CI_Upper"], bold=True),
    ])
    sem_row = " & ".join([
        ci(sem2["SGI"], sem2["CI_Lower"], sem2["CI_Upper"], bold=True),
        ci(li["academic_top100"]["semantic"]["0.5"]["SGI"],
           *li["academic_top100"]["semantic"]["0.5"]["CI"]),
        ci(hf["semantic"]["0.5"]["sgi"], *hf["semantic"]["0.5"]["ci"]),
        ci(sem4["SGI"], sem4["CI_Lower"], sem4["CI_Upper"], bold=True),
    ])
    body = (f"Lexical exact & {lex_row} \\\\" + chr(10) +
            f"SBERT $\\tau{{=}}0.5$ & {sem_row} \\\\")
    out = f"""% Matched-profile cross-corpus SGI (audit Phase 9/10).
% AUTO-GENERATED by experiments/make_latex.py -- do not edit by hand;
% tests/test_make_latex_regeneration.py asserts regeneration is byte-identical.
% Published ALIGN01/02 (HF, P=100) and ALIGN04 (LinkedIn, P=500) are bold;
% off-diagonal cells are audit reanalyses with identical tokenizer/model/seed
% (audit/_sgi_sensitivity/*.json).
\\begin{{tabular}}{{@{{}}lcccc@{{}}}}
\\toprule
& \\multicolumn{{2}}{{c}}{{\\textbf{{Academic $P=100$}}}} & \\multicolumn{{2}}{{c}}{{\\textbf{{Academic $P=500$}}}} \\\\
\\textbf{{Matcher}} & \\textbf{{HF}} & \\textbf{{LinkedIn}} & \\textbf{{HF}} & \\textbf{{LinkedIn}} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
"""
    (TAB / "tab_crosscorpus.tex").write_text(out, encoding="utf-8")



