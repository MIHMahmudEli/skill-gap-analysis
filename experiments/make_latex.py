"""Generate manuscript tables (.tex) and figures (.pdf) from verified results.

Reads results/<EXP_ID>/ outputs (all VERIFIED in results/registry.json) and
writes:
  paper/tables/*.tex   -- tabular fragments for \\input
  paper/figures/*.pdf  -- matplotlib figures

Every number in the generated artifacts therefore traces to a Kaggle GPU
experiment output archived at HF MoshinAli/skill-gap-experiments.
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib
