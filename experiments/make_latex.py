def check_tables() -> int:
    """Regenerate every table into a scratch directory and compare it with the
    committed files.  Writes NOTHING under paper/ or paper_placement/, so it is
    safe to run at any time (including on a reviewer's machine).  Exit code 1
    lists any table that regeneration would change -- i.e. a hand edit that the
    generator has not caught up with, or a generator that has drifted."""
    import tempfile
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        (td / "paper" / "tables").mkdir(parents=True)
        (td / "paper_placement" / "tables").mkdir(parents=True)
        globals_ = globals()
        saved = (globals_["TAB"], globals_["TABP"])
        try:
            globals_["TAB"] = td / "paper" / "tables"
            globals_["TABP"] = td / "paper_placement" / "tables"
            for fn in _all_table_fns():
                fn()
            scratch = {"paper": globals_["TAB"], "paper_placement": globals_["TABP"]}
        finally:
            globals_["TAB"], globals_["TABP"] = saved

        bad = []
        n = 0
        for sub, src in scratch.items():
            for p in sorted(src.glob("*.tex")):
                n += 1
                ref = ROOT / sub / "tables" / p.name
                if not ref.exists():
                    bad.append(f"no committed copy: {sub}/tables/{p.name}")
                elif p.read_text(encoding="utf-8") != ref.read_text(encoding="utf-8"):
                    bad.append(f"regeneration would change: {sub}/tables/{p.name}")
    if bad:
        print("CHECK FAILED (%d of %d tables differ):" % (len(bad), n))
        for b in bad:
            print("  -", b)
        return 1
    print(f"CHECK OK: all {n} tables regenerate byte-identically")
    return 0


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if "--check" in argv:
        return check_tables()

    for fn in _all_table_fns():
        fn()
    # Figure PDFs are committed artifacts with their metadata stripped
    # (save_figure); they are rewritten only on explicit request so that a
    # routine table regeneration cannot clobber them (footgun F-5).
    if "--figures" in argv:
        for fn in (fig_top_skills, fig_skill_gap, fig_geo_trends,
                   fig_placement, fig_internship):
            fn()
    print("tables:", sorted(p.name for p in TAB.glob("*.tex")))
    print("figures rewritten:", "--figures" in argv)
    return 0


