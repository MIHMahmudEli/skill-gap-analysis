def esc(s: str) -> str:
    return (str(s).replace("&", r"\&").replace("%", r"\%")
            .replace("_", r"\_").replace("#", r"\#"))


def anon_kernel(ref: str) -> str:
    """Double-blind: the Kaggle *namespace* identifies the author's accounts.

    The kernel slug (``sg-align01-lexical-a1``) carries no identity and is
    kept, so the table stays informative; the real ``namespace/slug`` pair
    lives in ``results/registry.json`` and ``results/worker_map.json``, which
    are not shipped with the papers.
    """
    return "anon/" + str(ref).split("/", 1)[1]


def load(exp: str) -> Path:
    reg = json.loads((RES / "registry.json").read_text(encoding="utf-8"))
    st = reg["experiments"][exp]["status"]
    assert st in ("VERIFIED", "USED_IN_MANUSCRIPT"), f"{exp} not verified: {st}"
    return RES / exp


