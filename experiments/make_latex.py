def tab_sensitivity() -> None:
    a2 = load("ALIGN02_semantic_sbert")
    a1 = load("ALIGN01_lexical_bootstrap")
    s = pd.read_csv(a2 / "table_sensitivity_tau.csv")
    m1 = json.loads((a1 / "metrics.json").read_text())
    label = {0.4: "Permissive", 0.5: "Baseline", 0.6: "Moderate", 0.7: "Strict"}
    rows = []
    for _, r in s.iterrows():
        tau = float(r["tau"])
        base = tau == 0.5
        f = lambda v: f"\\textbf{{{v}}}" if base else v
        rows.append(
            f"$\\tau = {tau:.1f}$ ({label[tau]}) & {f(f'{r['SGI']:.2f}')} & "
            f"{f(f'{r['Coverage_Rate']*100:.0f}\\%')} & "
            f"{f(f'[{r['CI_Lower']:.2f}, {r['CI_Upper']:.2f}]')} & "
            f"{f(f'{r['Delta_SGI']:+.2f}')} \\\\")
    rows.append(
        "\\textit{Lexical Match (Baseline)} & \\textit{%.2f} & "
        "\\textit{%.0f\\%%} & \\textit{[%.2f, %.2f]} & \\textit{+0.20} \\\\"
        % (m1["sgi"], m1["coverage_rate"] * 100,
           m1["sgi_ci_lower"], m1["sgi_ci_upper"]))
    body = "\n".join(rows)
    out = f"""% AUTO-GENERATED by experiments/make_latex.py -- do not edit
\\begin{{tabular}}{{@{{}}lcccc@{{}}}}
\\toprule
\\textbf{{Threshold $\\tau$}} & \\textbf{{SGI}} & \\textbf{{Coverage Rate}} & \\textbf{{95\\% Bootstrap CI}} & \\textbf{{$\\Delta$SGI}} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
"""
    (TAB / "tab_sensitivity.tex").write_text(out, encoding="utf-8")


