def fig_skill_gap() -> None:
    d = load("ALIGN03_domain_gap")
    g = pd.read_csv(d / "domain_gap_table.csv")
    short = {"Programming & Development": "Prog.",
             "Data Science & Analytics": "DataSci",
             "Cloud & Infrastructure": "Cloud",
             "Soft Skills": "SoftSk",
             "Business & Domain": "Business",
             "Design & UX": "Design",
             "Data Engineering": "DataEng",
             "Cybersecurity": "Cyber"}
    cats = [short[c] for c in g.category]
    x = np.arange(len(cats))
    w = 0.27

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(7.1, 2.9))
    ax1.bar(x - w, g.market_demand_pp, w, label="Market demand",
            color=BLUE, edgecolor="#123a5c", linewidth=0.4)
    ax1.bar(x, g.coverage_rate_lexical * 100, w, label="Coverage (lexical)",
            color=CYAN, edgecolor="#1a5c6e", linewidth=0.4)
    ax1.bar(x + w, g["coverage_rate_semantic_tau0.5"] * 100, w,
            label="Coverage (semantic)", color=GREEN,
            edgecolor="#14521b", linewidth=0.4)
    ax1.set_xticks(x, cats, rotation=35, ha="right")
    ax1.set_ylabel("Percent")
    ax1.set_ylim(0, 110)
    ax1.legend(loc="upper right", framealpha=0.9)
    ax1.set_title("(a) Demand vs. curriculum coverage")

    lo = g.deficit_pp_lexical - g.deficit_lex_ci_lower
    hi = g.deficit_lex_ci_upper - g.deficit_pp_lexical
    ax2.bar(x - w / 2, g.deficit_pp_lexical, w, yerr=[lo, hi],
            capsize=2, label="Lexical deficit", color=ORANGE,
            edgecolor="#7c3a00", linewidth=0.4, error_kw={"lw": 0.7})
    lo2 = g.deficit_pp_semantic - g.deficit_sem_ci_lower
    hi2 = g.deficit_sem_ci_upper - g.deficit_pp_semantic
    ax2.bar(x + w / 2, g.deficit_pp_semantic, w, yerr=[lo2, hi2],
            capsize=2, label="Semantic deficit", color=RED,
            edgecolor="#6e1414", linewidth=0.4, error_kw={"lw": 0.7})
    ax2.set_xticks(x, cats, rotation=35, ha="right")
    ax2.set_ylabel("Deficit (pp)")
    ax2.set_ylim(0, max(g.deficit_lex_ci_upper) * 1.3)
    ax2.legend(loc="upper right", framealpha=0.9)
    ax2.set_title("(b) Skill deficit magnitude (95% CI)")
    fig.tight_layout()
    fig.savefig(FIG / "fig2_skill_gap.pdf", bbox_inches="tight")
    plt.close(fig)


