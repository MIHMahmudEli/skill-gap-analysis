"""P5-4 (footguns F-5 / R-11): regeneration must never clobber verified
tables or the committed figure PDFs.

`python experiments/make_latex.py --check` regenerates all 14 tables into a
scratch directory and compares them with the committed files; it writes
nothing.  A non-zero exit means either the generator has drifted from what is
published, or someone hand-edited a table without updating the generator.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAKE = [sys.executable, str(ROOT / "experiments" / "make_latex.py")]
TABLE_DIRS = [ROOT / "paper" / "tables", ROOT / "paper_placement" / "tables"]


def _run(*args):
    return subprocess.run(MAKE + list(args), capture_output=True, text=True,
                          cwd=str(ROOT))


def test_tables_regenerate_byte_identically():
    r = _run("--check")
    assert r.returncode == 0, f"regeneration would change a verified table:\n{r.stdout}{r.stderr}"
    assert "CHECK OK" in r.stdout


def test_check_mode_writes_nothing():
    """--check must leave every committed table byte-for-byte untouched."""
    def snap():
        return {p: p.read_bytes() for d in TABLE_DIRS for p in d.glob("*.tex")}
    before = snap()
    assert _run("--check").returncode == 0
    assert snap() == before, "check mode modified a committed table"


def test_crosscorpus_is_generated_not_hand_maintained():
    """R-11: the cross-corpus table must be a generator product (the old
    generator silently lost to a hand edit, so the two had diverged)."""
    src = (ROOT / "experiments" / "make_latex.py").read_text(encoding="utf-8")
    assert 'TAB / "tab_crosscorpus.tex"' in src
    tbl = (ROOT / "paper" / "tables" / "tab_crosscorpus.tex").read_text(encoding="utf-8")
    assert "AUTO-GENERATED by experiments/make_latex.py" in tbl
    # the four published cells and their bolding must survive
    for cell in (r"\textbf{0.52 [0.42, 0.63]}", "0.52 [0.42, 0.62]",
                 r"\textbf{0.37 [0.28, 0.47]}", "0.37 [0.28, 0.47]",
                 r"\textbf{0.32 [0.23, 0.41]}", "0.32 [0.23, 0.42]",
                 r"\textbf{0.14 [0.07, 0.21]}", "0.14 [0.08, 0.21]"):
        assert cell in tbl, cell


def test_figures_carry_no_pdf_metadata():
    """Step-6 regression guard: figure PDFs must not carry /CreationDate (its
    default value leaks the build machine's timezone), /ModDate or the
    matplotlib identity strings."""
    figs = sorted((ROOT / "paper" / "figures").glob("*.pdf"))
    assert figs, "no committed figure PDFs found"
    for p in figs:
        data = p.read_bytes()
        for marker in (b"/CreationDate", b"/ModDate", b"/Author", b"/Matplotlib"):
            assert marker not in data, f"{p.name} carries {marker.decode()}"


def test_default_run_does_not_write_figures():
    """F-5: a plain table regeneration must not rewrite figure PDFs."""
    src = (ROOT / "experiments" / "make_latex.py").read_text(encoding="utf-8")
    main_src = src[src.index("def main("):]
    fig_block = main_src[:main_src.index('if "--figures" in argv:')]
    assert "fig_top_skills" not in fig_block and "fig_internship" not in fig_block, \
        "figure generation must sit behind the --figures flag"
